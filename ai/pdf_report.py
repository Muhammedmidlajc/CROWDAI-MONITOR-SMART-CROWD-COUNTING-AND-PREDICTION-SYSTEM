import os
from datetime import datetime

from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import (
    SimpleDocTemplate,
    Paragraph,
    Spacer,
    Image,
    Table,
    TableStyle,
)


def generate_pdf(
    pdf_path,
    original_image,
    heatmap_image,
    people_count,
    density_level,
):
    """
    Generate Crowd Density Prediction Report
    """

    doc = SimpleDocTemplate(pdf_path)

    styles = getSampleStyleSheet()

    elements = []

    # ------------------------
    # Title
    # ------------------------

    elements.append(
        Paragraph(
            "<b><font size=18>AI Crowd Density Estimation Report</font></b>",
            styles["Title"],
        )
    )

    elements.append(Spacer(1, 20))

    # ------------------------
    # Date
    # ------------------------

    now = datetime.now()

    elements.append(
        Paragraph(
            f"<b>Date:</b> {now.strftime('%d-%m-%Y')}",
            styles["Normal"],
        )
    )

    elements.append(
        Paragraph(
            f"<b>Time:</b> {now.strftime('%I:%M %p')}",
            styles["Normal"],
        )
    )

    elements.append(Spacer(1, 20))

    # ------------------------
    # Result Table
    # ------------------------

    table_data = [
        ["Estimated Crowd", str(people_count)],
        ["Density Level", density_level],
        ["Model", "Enhanced MC-CNN + MobileNetV2"],
    ]

    table = Table(table_data, colWidths=[180, 220])

    table.setStyle(
        TableStyle(
            [
                ("GRID", (0, 0), (-1, -1), 1, colors.black),
                ("BACKGROUND", (0, 0), (0, -1), colors.lightgrey),
                ("FONTNAME", (0, 0), (-1, -1), "Helvetica-Bold"),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 10),
            ]
        )
    )

    elements.append(table)

    elements.append(Spacer(1, 25))

    # ------------------------
    # Original Image
    # ------------------------

    elements.append(
        Paragraph("<b>Original Image</b>", styles["Heading2"])
    )

    elements.append(Image(original_image, width=250, height=180))

    elements.append(Spacer(1, 20))

    # ------------------------
    # Heatmap
    # ------------------------

    elements.append(
        Paragraph("<b>Density Heatmap</b>", styles["Heading2"])
    )

    elements.append(Image(heatmap_image, width=250, height=180))

    elements.append(Spacer(1, 20))

    # ------------------------
    # Footer
    # ------------------------

    elements.append(
        Paragraph(
            "Generated by AI Crowd Density Estimation System",
            styles["Italic"],
        )
    )

    doc.build(elements)